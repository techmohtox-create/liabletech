-- Freight Chaser: trucks, drivers, trips with their proof of delivery, invoices and follow-ups.

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    registration VARCHAR(20) NOT NULL,
    description VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (account_id, registration)
);

-- A driver's mobile is unique across all fleets: it is how a WhatsApp photo finds its fleet.
CREATE TABLE driver (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    vehicle_id BIGINT REFERENCES vehicle (id),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- The transporter, broker or consignor who pays the freight.
CREATE TABLE party (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(100),
    phone VARCHAR(20),
    email VARCHAR(200),
    gstin VARCHAR(15),
    address VARCHAR(500),
    credit_days INT NOT NULL DEFAULT 30,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    lr_number VARCHAR(50),
    lr_date DATE,
    party_id BIGINT REFERENCES party (id),
    vehicle_id BIGINT REFERENCES vehicle (id),
    driver_id BIGINT REFERENCES driver (id),
    origin VARCHAR(100),
    destination VARCHAR(100),
    consignee VARCHAR(150),
    goods VARCHAR(200),
    freight_amount NUMERIC(12, 2),
    advance_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    detention_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    other_charges NUMERIC(12, 2) NOT NULL DEFAULT 0,
    delivered_on DATE,
    status VARCHAR(20) NOT NULL,
    invoice_id BIGINT,
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX trip_account_status ON trip (account_id, status);
CREATE INDEX trip_account_lr ON trip (account_id, lr_number);

-- A photo or scan of the signed lorry receipt, and what was read from it.
CREATE TABLE pod (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    trip_id BIGINT REFERENCES trip (id),
    file_id BIGINT NOT NULL REFERENCES stored_file (id),
    driver_id BIGINT REFERENCES driver (id),
    source VARCHAR(20) NOT NULL,
    caption VARCHAR(500),
    reading_status VARCHAR(20) NOT NULL,
    reading_note VARCHAR(500),
    document_type VARCHAR(20),
    lr_number VARCHAR(50),
    lr_date DATE,
    delivery_date DATE,
    consignor VARCHAR(150),
    consignee VARCHAR(150),
    origin VARCHAR(100),
    destination VARCHAR(100),
    vehicle_number VARCHAR(20),
    packages VARCHAR(60),
    freight_amount NUMERIC(12, 2),
    stamp_present BOOLEAN,
    signature_present BOOLEAN,
    remarks VARCHAR(500),
    confidence NUMERIC(3, 2),
    review_status VARCHAR(20) NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX pod_account_review ON pod (account_id, review_status, received_at);

CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    number VARCHAR(30) NOT NULL,
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    party_id BIGINT NOT NULL REFERENCES party (id),
    subtotal NUMERIC(12, 2) NOT NULL,
    gst_mode VARCHAR(20) NOT NULL,
    gst_rate NUMERIC(5, 2) NOT NULL DEFAULT 0,
    cgst NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sgst NUMERIC(12, 2) NOT NULL DEFAULT 0,
    igst NUMERIC(12, 2) NOT NULL DEFAULT 0,
    round_off NUMERIC(6, 2) NOT NULL DEFAULT 0,
    advance_received NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total NUMERIC(12, 2) NOT NULL,
    received NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tds NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    pdf_file_id BIGINT REFERENCES stored_file (id),
    sent_at TIMESTAMP WITH TIME ZONE,
    paid_on DATE,
    chase_paused BOOLEAN NOT NULL DEFAULT FALSE,
    promised_on DATE,
    next_follow_up_on DATE,
    follow_up_count INT NOT NULL DEFAULT 0,
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, number)
);
CREATE INDEX invoice_account_status ON invoice (account_id, status);
ALTER TABLE trip ADD CONSTRAINT trip_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (id);

CREATE TABLE invoice_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoice (id),
    trip_id BIGINT REFERENCES trip (id),
    description VARCHAR(300) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    position INT NOT NULL
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    invoice_id BIGINT NOT NULL REFERENCES invoice (id),
    received_on DATE NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    tds NUMERIC(12, 2) NOT NULL DEFAULT 0,
    mode VARCHAR(20) NOT NULL,
    reference VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Everything that happened while chasing an invoice: sends, automatic reminders, calls, promises.
CREATE TABLE follow_up (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    invoice_id BIGINT NOT NULL REFERENCES invoice (id),
    happened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    kind VARCHAR(20) NOT NULL,
    stage INT,
    note VARCHAR(1000),
    outbound_message_id BIGINT REFERENCES outbound_message (id)
);
CREATE INDEX follow_up_invoice ON follow_up (invoice_id, happened_at);

CREATE TABLE chase_settings (
    account_id BIGINT PRIMARY KEY REFERENCES account (id),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reminder_days VARCHAR(100) NOT NULL,
    repeat_every_days INT NOT NULL DEFAULT 15,
    send_whatsapp BOOLEAN NOT NULL DEFAULT TRUE,
    send_email BOOLEAN NOT NULL DEFAULT TRUE,
    default_gst_mode VARCHAR(20) NOT NULL DEFAULT 'NONE',
    default_gst_rate NUMERIC(5, 2) NOT NULL DEFAULT 5,
    invoice_prefix VARCHAR(10) NOT NULL DEFAULT 'FC',
    invoice_terms VARCHAR(1000),
    owner_digest BOOLEAN NOT NULL DEFAULT TRUE
);
