-- Tables every app shares. Written for PostgreSQL; local runs use H2 in PostgreSQL mode.

-- One row per business that signs up (a fleet, a builder, an exporter, a service business, a shop).
CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    owner_name VARCHAR(100),
    phone VARCHAR(20),
    email VARCHAR(200),
    address VARCHAR(500),
    gstin VARCHAR(15),
    pan VARCHAR(10),
    upi_id VARCHAR(100),
    bank_account_name VARCHAR(150),
    bank_account_number VARCHAR(30),
    bank_ifsc VARCHAR(11),
    bank_name VARCHAR(100),
    -- Set only when the business has its own WhatsApp Business number on the Cloud API.
    whatsapp_phone_number_id VARCHAR(50) UNIQUE,
    plan_code VARCHAR(30) NOT NULL,
    trial_ends_on DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stored_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT REFERENCES account (id),
    storage_key VARCHAR(200) NOT NULL UNIQUE,
    original_name VARCHAR(255),
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX stored_file_account ON stored_file (account_id, created_at);

-- Every WhatsApp message received, from the Cloud API webhook or the local simulator.
CREATE TABLE wa_inbound (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT REFERENCES account (id),
    wa_message_id VARCHAR(150) NOT NULL UNIQUE,
    from_phone VARCHAR(20) NOT NULL,
    to_phone_number_id VARCHAR(50),
    contact_name VARCHAR(100),
    message_type VARCHAR(20) NOT NULL,
    text_body VARCHAR(4000),
    media_id VARCHAR(100),
    media_mime_type VARCHAR(100),
    media_filename VARCHAR(255),
    file_id BIGINT REFERENCES stored_file (id),
    context_wa_message_id VARCHAR(150),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    error VARCHAR(1000),
    processed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX wa_inbound_status ON wa_inbound (status, received_at);
CREATE INDEX wa_inbound_from ON wa_inbound (from_phone, received_at);

-- Every WhatsApp message and email sent, whether delivered for real or only simulated locally.
CREATE TABLE outbound_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT REFERENCES account (id),
    channel VARCHAR(10) NOT NULL,
    recipient VARCHAR(200) NOT NULL,
    subject VARCHAR(300),
    body VARCHAR(8000) NOT NULL,
    attachment_file_ids VARCHAR(200),
    template_name VARCHAR(100),
    status VARCHAR(20) NOT NULL,
    provider_message_id VARCHAR(150),
    error VARCHAR(1000),
    related_type VARCHAR(40),
    related_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_updated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX outbound_account ON outbound_message (account_id, created_at);
CREATE INDEX outbound_recipient ON outbound_message (recipient, created_at);
CREATE INDEX outbound_provider ON outbound_message (provider_message_id);

-- One row per call to the document-reading model, for cost tracking per account.
CREATE TABLE ai_call (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT REFERENCES account (id),
    purpose VARCHAR(50) NOT NULL,
    model VARCHAR(60),
    outcome VARCHAR(20) NOT NULL,
    input_tokens INT,
    output_tokens INT,
    duration_ms INT,
    error VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ai_call_account ON ai_call (account_id, created_at);

-- Gapless numbering for invoices and other documents, per Indian financial year.
CREATE TABLE doc_sequence (
    account_id BIGINT NOT NULL REFERENCES account (id),
    series VARCHAR(30) NOT NULL,
    period VARCHAR(10) NOT NULL,
    next_value INT NOT NULL,
    PRIMARY KEY (account_id, series, period)
);
