-- AMC Renewals: customers' appliances, annual maintenance contracts, reminders and the requests they bring.

CREATE TABLE technician (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(150),
    phone VARCHAR(20) NOT NULL,
    address VARCHAR(300),
    area VARCHAR(100),
    opted_out BOOLEAN NOT NULL DEFAULT FALSE,
    notes VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX customer_phone ON customer (account_id, phone);
CREATE INDEX customer_by_phone ON customer (phone);

CREATE TABLE appliance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    customer_id BIGINT NOT NULL REFERENCES customer (id),
    -- SPLIT_AC, WINDOW_AC, CASSETTE_AC, RO, WATER_HEATER, REFRIGERATOR, WASHING_MACHINE, CHIMNEY, OTHER
    kind VARCHAR(20) NOT NULL,
    brand VARCHAR(60),
    model VARCHAR(80),
    serial_number VARCHAR(80),
    capacity VARCHAR(40),
    refrigerant VARCHAR(20),
    manufactured VARCHAR(20),
    location VARCHAR(60),
    label_file_id BIGINT REFERENCES stored_file (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX appliance_customer ON appliance (customer_id);

CREATE TABLE amc_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    -- AC, RO, WATER_HEATER, ANY
    family VARCHAR(20) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    months INT NOT NULL,
    visits INT NOT NULL,
    covers VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE contract (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    customer_id BIGINT NOT NULL REFERENCES customer (id),
    appliance_id BIGINT NOT NULL REFERENCES appliance (id),
    plan_id BIGINT REFERENCES amc_plan (id),
    plan_name VARCHAR(100) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    visits_included INT NOT NULL,
    -- ACTIVE (including expired, not yet renewed), RENEWED, CANCELLED
    status VARCHAR(20) NOT NULL,
    renewed_by_id BIGINT,
    renewal_token VARCHAR(40) NOT NULL UNIQUE,
    paid_amount NUMERIC(10, 2),
    paid_on DATE,
    payment_mode VARCHAR(20),
    -- TECHNICIAN, OFFICE, RENEWAL
    source VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX contract_ends ON contract (account_id, status, ends_on);
CREATE INDEX contract_customer ON contract (customer_id);

-- One row per reminder sent, so each is sent once.
CREATE TABLE reminder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    contract_id BIGINT NOT NULL REFERENCES contract (id),
    -- RENEWAL (offset_days from the end date) or SERVICE (offset_days = visit number)
    kind VARCHAR(20) NOT NULL,
    offset_days INT NOT NULL,
    due_on DATE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    outbound_id BIGINT,
    UNIQUE (contract_id, kind, offset_days)
);
CREATE INDEX reminder_account ON reminder (account_id, sent_at);

CREATE TABLE reminder_settings (
    account_id BIGINT PRIMARY KEY REFERENCES account (id),
    renewal_offsets VARCHAR(100) NOT NULL,
    service_reminders BOOLEAN NOT NULL,
    auto_send BOOLEAN NOT NULL
);

-- A renewal or a service visit someone asked for: the customer from the link or on WhatsApp, or the office.
CREATE TABLE service_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    customer_id BIGINT NOT NULL REFERENCES customer (id),
    contract_id BIGINT REFERENCES contract (id),
    appliance_id BIGINT REFERENCES appliance (id),
    -- RENEWAL, SERVICE, REPAIR
    kind VARCHAR(20) NOT NULL,
    -- LINK, WHATSAPP, OFFICE
    source VARCHAR(20) NOT NULL,
    -- NEW, SCHEDULED, DONE, DISMISSED
    status VARCHAR(20) NOT NULL,
    plan_id BIGINT REFERENCES amc_plan (id),
    preferred_on DATE,
    preferred_slot VARCHAR(20),
    scheduled_on DATE,
    technician_id BIGINT REFERENCES technician (id),
    note VARCHAR(500),
    done_on DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX service_request_account ON service_request (account_id, status, created_at);

-- A label photo from a technician, before it becomes an appliance.
CREATE TABLE label_scan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    technician_id BIGINT REFERENCES technician (id),
    file_id BIGINT NOT NULL REFERENCES stored_file (id),
    caption VARCHAR(500),
    -- READ, MANUAL
    reading_status VARCHAR(20) NOT NULL,
    reading_note VARCHAR(500),
    kind VARCHAR(20),
    brand VARCHAR(60),
    model VARCHAR(80),
    serial_number VARCHAR(80),
    capacity VARCHAR(40),
    refrigerant VARCHAR(20),
    manufactured VARCHAR(20),
    customer_phone VARCHAR(20),
    customer_name VARCHAR(150),
    amc_sold BOOLEAN NOT NULL DEFAULT FALSE,
    amount NUMERIC(10, 2),
    confidence NUMERIC(3, 2),
    -- NEEDS_REVIEW, LINKED, REJECTED
    status VARCHAR(20) NOT NULL,
    appliance_id BIGINT REFERENCES appliance (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX label_scan_account ON label_scan (account_id, status, created_at);
