-- Part Finder: the shop's stock and what each part fits, mechanics' enquiries, the quotes sent back
-- and the bookings they turn into.

CREATE TABLE part (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    -- the number on the box, the shop's own code if it has none
    part_number VARCHAR(60) NOT NULL,
    name VARCHAR(150) NOT NULL,
    -- PartType: BRAKE_PAD, CLUTCH_PLATE, OIL_FILTER...
    category VARCHAR(30) NOT NULL,
    brand VARCHAR(60),
    -- numbers it replaces (maker's and other brands'), comma separated
    alt_numbers VARCHAR(300),
    price NUMERIC(10, 2) NOT NULL,
    mrp NUMERIC(10, 2),
    stock INT NOT NULL DEFAULT 0,
    rack VARCHAR(30),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX part_number_unique ON part (account_id, part_number);
CREATE INDEX part_category ON part (account_id, category);

-- One vehicle a part fits; years are inclusive and either end may be open.
CREATE TABLE fitment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id BIGINT NOT NULL REFERENCES part (id) ON DELETE CASCADE,
    make VARCHAR(40),
    model VARCHAR(60) NOT NULL,
    year_from INT,
    year_to INT,
    variant VARCHAR(60)
);
CREATE INDEX fitment_part ON fitment (part_id);

CREATE TABLE mechanic (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    phone VARCHAR(20) NOT NULL,
    name VARCHAR(150),
    garage VARCHAR(150),
    area VARCHAR(100),
    notes VARCHAR(500),
    blocked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX mechanic_phone ON mechanic (account_id, phone);
CREATE INDEX mechanic_by_phone ON mechanic (phone);

CREATE TABLE enquiry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    mechanic_id BIGINT NOT NULL REFERENCES mechanic (id),
    inbound_id BIGINT,
    -- PHOTO, VOICE, TEXT
    kind VARCHAR(10) NOT NULL,
    file_id BIGINT REFERENCES stored_file (id),
    text VARCHAR(1000),
    transcript VARCHAR(2000),
    -- READ (by the AI), PARSED (from the words, no AI), EDITED (by the counter), MANUAL (nothing understood)
    reading_status VARCHAR(10) NOT NULL,
    reading_note VARCHAR(500),
    part_type VARCHAR(30),
    part_name VARCHAR(150),
    part_numbers VARCHAR(300),
    vehicle_make VARCHAR(40),
    vehicle_model VARCHAR(60),
    vehicle_year INT,
    position VARCHAR(20),
    quantity INT NOT NULL DEFAULT 1,
    confidence NUMERIC(3, 2),
    question VARCHAR(300),
    -- NEW, QUOTED, BOOKED, NOT_AVAILABLE, CLOSED
    status VARCHAR(20) NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- the first answer that was more than "got it": a quote, "not in stock" or a question
    first_reply_at TIMESTAMP WITH TIME ZONE,
    -- AUTO or STAFF
    replied_by VARCHAR(10),
    nudged_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX enquiry_account ON enquiry (account_id, status, received_at);
CREATE INDEX enquiry_mechanic ON enquiry (mechanic_id, received_at);

-- An option offered in a reply: "1) ProStop front pads ₹1,150".
CREATE TABLE quote_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_id BIGINT NOT NULL REFERENCES enquiry (id),
    option_no INT NOT NULL,
    part_id BIGINT REFERENCES part (id),
    description VARCHAR(200) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (enquiry_id, option_no)
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    enquiry_id BIGINT REFERENCES enquiry (id),
    mechanic_id BIGINT NOT NULL REFERENCES mechanic (id),
    part_id BIGINT REFERENCES part (id),
    description VARCHAR(200) NOT NULL,
    quantity INT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    -- BOOKED (stock set aside), HANDED_OVER, CANCELLED
    status VARCHAR(20) NOT NULL,
    payment_mode VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    done_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX booking_account ON booking (account_id, status, created_at);

CREATE TABLE shop_settings (
    account_id BIGINT PRIMARY KEY REFERENCES account (id),
    -- "Got it, checking" with the guess, as soon as an enquiry arrives
    acknowledge BOOLEAN NOT NULL,
    -- Pro: answer confident matches with a quote straight away
    auto_quote BOOLEAN NOT NULL,
    auto_quote_confidence NUMERIC(3, 2) NOT NULL,
    -- Pro: tell the owner on WhatsApp when an enquiry has waited this long (0 = off)
    nudge_minutes INT NOT NULL,
    ready_minutes INT NOT NULL
);
