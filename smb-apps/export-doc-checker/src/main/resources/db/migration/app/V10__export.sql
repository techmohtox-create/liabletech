-- Export Doc Checker: shipments under a letter of credit, their documents as read, and what the check found.

-- People who may send documents on WhatsApp for the business.
CREATE TABLE doc_sender (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One export shipment presented under one letter of credit. The LC fields are copied here from the
-- LC reading so lists and deadlines need no JSON.
CREATE TABLE shipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    reference VARCHAR(40) NOT NULL,
    title VARCHAR(150),
    buyer_name VARCHAR(200),
    buyer_email VARCHAR(200),
    lc_number VARCHAR(60),
    issuing_bank VARCHAR(200),
    currency VARCHAR(3),
    lc_amount NUMERIC(16, 2),
    lc_expiry DATE,
    latest_shipment DATE,
    shipped_on DATE,
    presentation_deadline DATE,
    planned_presentation DATE,
    forwarder_name VARCHAR(150),
    forwarder_phone VARCHAR(20),
    forwarder_email VARCHAR(200),
    -- COLLECTING, CHECKED, READY, SUBMITTED, PAID, CANCELLED
    status VARCHAR(20) NOT NULL,
    critical_count INT NOT NULL DEFAULT 0,
    warning_count INT NOT NULL DEFAULT 0,
    first_checked_at TIMESTAMP WITH TIME ZONE,
    checked_at TIMESTAMP WITH TIME ZONE,
    submitted_on DATE,
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX shipment_reference ON shipment (account_id, reference);
CREATE INDEX shipment_account ON shipment (account_id, status, updated_at);

-- A document of the shipment and what was read from it, as JSON of the reading record for its type.
CREATE TABLE shipment_doc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    shipment_id BIGINT NOT NULL REFERENCES shipment (id),
    -- LC, INVOICE, PACKING_LIST, TRANSPORT, ORIGIN, INSURANCE, OTHER
    doc_type VARCHAR(20) NOT NULL,
    file_id BIGINT REFERENCES stored_file (id),
    source VARCHAR(20) NOT NULL,
    -- READ (by AI), PARSED (SWIFT text), MANUAL (typed in), EDITED (read, then corrected)
    reading_status VARCHAR(20) NOT NULL,
    reading_note VARCHAR(500),
    data_json TEXT,
    confidence NUMERIC(3, 2),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX shipment_doc_shipment ON shipment_doc (shipment_id, doc_type);

-- A discrepancy or point to check. The fingerprint keeps the exporter's decisions (accepted, fixed)
-- across re-checks.
CREATE TABLE finding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    shipment_id BIGINT NOT NULL REFERENCES shipment (id),
    -- CRITICAL (the bank will call it a discrepancy), WARNING (likely to be queried), INFO
    severity VARCHAR(10) NOT NULL,
    code VARCHAR(40) NOT NULL,
    fingerprint VARCHAR(200) NOT NULL,
    title VARCHAR(200) NOT NULL,
    detail VARCHAR(2000) NOT NULL,
    expected VARCHAR(1000),
    found VARCHAR(1000),
    documents VARCHAR(100),
    rule_ref VARCHAR(100),
    -- EXPORTER, FORWARDER, BUYER, INSURER, CHAMBER
    fixer VARCHAR(20) NOT NULL,
    fix VARCHAR(500),
    -- OPEN, ACCEPTED, FIXED
    status VARCHAR(20) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX finding_shipment ON finding (shipment_id, status);
