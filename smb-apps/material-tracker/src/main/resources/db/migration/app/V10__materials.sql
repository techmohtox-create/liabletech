-- Material Tracker: what arrives at each site, what suppliers bill, and the gaps between the two.

CREATE TABLE site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(150) NOT NULL,
    location VARCHAR(200),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Supervisors and storekeepers who photograph delivery slips. The phone decides the builder.
CREATE TABLE site_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    site_id BIGINT NOT NULL REFERENCES site (id),
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(200),
    gstin VARCHAR(15),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The builder's own list of materials, with the words suppliers use for them on slips and bills.
CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    name VARCHAR(100) NOT NULL,
    category VARCHAR(20) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    aliases VARCHAR(500),
    bag_kg NUMERIC(6, 2),
    bar_diameter_mm INT,
    tolerance_pct NUMERIC(5, 2) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Rates agreed with a supplier, per unit, before GST.
CREATE TABLE rate_agreement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    supplier_id BIGINT NOT NULL REFERENCES supplier (id),
    material_id BIGINT NOT NULL REFERENCES material (id),
    rate NUMERIC(12, 2) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE
);

-- A delivery at a site: the photographed challan, and what the supervisor counted.
CREATE TABLE delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    site_id BIGINT NOT NULL REFERENCES site (id),
    supplier_id BIGINT REFERENCES supplier (id),
    member_id BIGINT REFERENCES site_member (id),
    file_id BIGINT REFERENCES stored_file (id),
    source VARCHAR(20) NOT NULL,
    caption VARCHAR(500),
    reading_status VARCHAR(20) NOT NULL,
    reading_note VARCHAR(500),
    supplier_name_read VARCHAR(150),
    challan_number VARCHAR(50),
    challan_date DATE,
    vehicle_number VARCHAR(20),
    confidence NUMERIC(3, 2),
    status VARCHAR(20) NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    notes VARCHAR(500)
);
CREATE INDEX delivery_account_status ON delivery (account_id, status);
CREATE INDEX delivery_member ON delivery (member_id, status);

CREATE TABLE delivery_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL REFERENCES delivery (id),
    line_no INT NOT NULL,
    material_id BIGINT REFERENCES material (id),
    description VARCHAR(200) NOT NULL,
    slip_qty NUMERIC(14, 3),
    unit VARCHAR(10),
    received_qty NUMERIC(14, 3)
);

CREATE TABLE supplier_bill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    site_id BIGINT REFERENCES site (id),
    supplier_id BIGINT REFERENCES supplier (id),
    file_id BIGINT REFERENCES stored_file (id),
    source VARCHAR(20) NOT NULL,
    reading_status VARCHAR(20) NOT NULL,
    reading_note VARCHAR(500),
    supplier_name_read VARCHAR(150),
    bill_number VARCHAR(50),
    bill_date DATE,
    challan_refs VARCHAR(500),
    taxable_amount NUMERIC(14, 2),
    tax_amount NUMERIC(14, 2),
    total_amount NUMERIC(14, 2),
    confidence NUMERIC(3, 2),
    status VARCHAR(20) NOT NULL,
    checked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX supplier_bill_account_status ON supplier_bill (account_id, status);

CREATE TABLE bill_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES supplier_bill (id),
    line_no INT NOT NULL,
    material_id BIGINT REFERENCES material (id),
    description VARCHAR(200) NOT NULL,
    qty NUMERIC(14, 3),
    unit VARCHAR(10),
    rate NUMERIC(12, 2),
    amount NUMERIC(14, 2),
    challan_ref VARCHAR(50)
);

-- Which deliveries a bill was checked against.
CREATE TABLE bill_delivery (
    bill_id BIGINT NOT NULL REFERENCES supplier_bill (id),
    delivery_id BIGINT NOT NULL REFERENCES delivery (id),
    PRIMARY KEY (bill_id, delivery_id)
);

-- A gap found between what arrived, what was agreed and what was billed, with its rupee impact.
CREATE TABLE leakage_flag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account (id),
    site_id BIGINT REFERENCES site (id),
    supplier_id BIGINT REFERENCES supplier (id),
    bill_id BIGINT REFERENCES supplier_bill (id),
    delivery_id BIGINT REFERENCES delivery (id),
    material_id BIGINT REFERENCES material (id),
    kind VARCHAR(30) NOT NULL,
    message VARCHAR(500) NOT NULL,
    expected_qty NUMERIC(14, 3),
    actual_qty NUMERIC(14, 3),
    unit VARCHAR(10),
    amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolution_note VARCHAR(500)
);
CREATE INDEX leakage_flag_account_status ON leakage_flag (account_id, status);
CREATE INDEX leakage_flag_bill ON leakage_flag (bill_id);
