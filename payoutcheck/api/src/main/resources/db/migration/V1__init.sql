-- PayoutCheck schema. Portable between PostgreSQL (production) and H2 in PostgreSQL mode (local).
-- Every business table carries org_id: all reads are scoped to the signed-in user's organisation.

CREATE TABLE organization (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(160) NOT NULL,
    plan        VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         BIGINT       NOT NULL REFERENCES organization (id),
    email          VARCHAR(254) NOT NULL UNIQUE,
    full_name      VARCHAR(120) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    active         BOOLEAN      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE outlet (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT       NOT NULL REFERENCES organization (id),
    name        VARCHAR(120) NOT NULL,
    city        VARCHAR(80),
    swiggy_id   VARCHAR(40),
    zomato_id   VARCHAR(40),
    active      BOOLEAN      NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- The contract each outlet has with each platform. The reconciliation engine checks every
-- statement line against these rates.
CREATE TABLE platform_terms (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id                BIGINT        NOT NULL REFERENCES outlet (id),
    platform                 VARCHAR(10)   NOT NULL,
    commission_pct           NUMERIC(6, 3) NOT NULL,
    pg_fee_pct               NUMERIC(6, 3) NOT NULL,
    gst_on_fees_pct          NUMERIC(6, 3) NOT NULL,
    tcs_pct                  NUMERIC(6, 3) NOT NULL,
    tds_pct                  NUMERIC(6, 3) NOT NULL,
    commission_on_packaging  BOOLEAN       NOT NULL,
    tolerance                NUMERIC(8, 2) NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_terms_outlet_platform UNIQUE (outlet_id, platform)
);

CREATE TABLE import_batch (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         BIGINT       NOT NULL REFERENCES organization (id),
    outlet_id      BIGINT       NOT NULL REFERENCES outlet (id),
    kind           VARCHAR(12)  NOT NULL,
    platform       VARCHAR(10)  NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    rows_total     INT          NOT NULL,
    rows_imported  INT          NOT NULL,
    rows_rejected  INT          NOT NULL,
    errors         VARCHAR(8000),
    created_by     BIGINT REFERENCES app_user (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Orders as the restaurant recorded them (POS or the platform's own order history export).
CREATE TABLE order_record (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id               BIGINT         NOT NULL REFERENCES organization (id),
    outlet_id            BIGINT         NOT NULL REFERENCES outlet (id),
    platform             VARCHAR(10)    NOT NULL,
    order_ref            VARCHAR(60)    NOT NULL,
    ordered_at           TIMESTAMP      NOT NULL,
    status               VARCHAR(12)    NOT NULL,
    item_total           NUMERIC(12, 2) NOT NULL,
    packaging            NUMERIC(12, 2) NOT NULL,
    restaurant_discount  NUMERIC(12, 2) NOT NULL,
    import_id            BIGINT REFERENCES import_batch (id),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_order UNIQUE (outlet_id, platform, order_ref)
);
CREATE INDEX ix_order_period ON order_record (outlet_id, platform, ordered_at);

CREATE TABLE payout_statement (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id           BIGINT         NOT NULL REFERENCES organization (id),
    outlet_id        BIGINT         NOT NULL REFERENCES outlet (id),
    platform         VARCHAR(10)    NOT NULL,
    period_start     DATE           NOT NULL,
    period_end       DATE           NOT NULL,
    payout_date      DATE,
    utr              VARCHAR(40),
    credited_amount  NUMERIC(12, 2),
    file_name        VARCHAR(255)   NOT NULL,
    import_id        BIGINT REFERENCES import_batch (id),
    line_count       INT            NOT NULL,
    gross_sales      NUMERIC(14, 2) NOT NULL,
    total_deductions NUMERIC(14, 2) NOT NULL,
    net_payout       NUMERIC(14, 2) NOT NULL,
    checked_at       TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_statement_period UNIQUE (outlet_id, platform, period_start, period_end)
);

CREATE TABLE statement_line (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id            BIGINT         NOT NULL REFERENCES payout_statement (id) ON DELETE CASCADE,
    line_no                 INT            NOT NULL,
    order_ref               VARCHAR(60),
    order_date              DATE,
    order_status            VARCHAR(12),
    item_total              NUMERIC(12, 2) NOT NULL,
    packaging               NUMERIC(12, 2) NOT NULL,
    restaurant_discount     NUMERIC(12, 2) NOT NULL,
    commission              NUMERIC(12, 2) NOT NULL,
    pg_fee                  NUMERIC(12, 2) NOT NULL,
    other_fees              NUMERIC(12, 2) NOT NULL,
    gst_on_fees             NUMERIC(12, 2) NOT NULL,
    tcs                     NUMERIC(12, 2) NOT NULL,
    tds                     NUMERIC(12, 2) NOT NULL,
    customer_refund         NUMERIC(12, 2) NOT NULL,
    cancellation_deduction  NUMERIC(12, 2) NOT NULL,
    penalty                 NUMERIC(12, 2) NOT NULL,
    other_adjustment        NUMERIC(12, 2) NOT NULL,
    net_payout              NUMERIC(12, 2) NOT NULL,
    description             VARCHAR(255)
);
CREATE INDEX ix_line_statement ON statement_line (statement_id);
CREATE INDEX ix_line_order ON statement_line (order_ref);

-- A deduction or gap the engine thinks is worth disputing, and where the dispute stands.
CREATE TABLE finding (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id            BIGINT         NOT NULL REFERENCES organization (id),
    outlet_id         BIGINT         NOT NULL REFERENCES outlet (id),
    statement_id      BIGINT         NOT NULL REFERENCES payout_statement (id) ON DELETE CASCADE,
    line_id           BIGINT REFERENCES statement_line (id) ON DELETE SET NULL,
    platform          VARCHAR(10)    NOT NULL,
    order_ref         VARCHAR(60),
    type              VARCHAR(40)    NOT NULL,
    severity          VARCHAR(10)    NOT NULL,
    expected_amount   NUMERIC(12, 2),
    actual_amount     NUMERIC(12, 2),
    amount_at_risk    NUMERIC(12, 2) NOT NULL,
    explanation       VARCHAR(1000)  NOT NULL,
    status            VARCHAR(12)    NOT NULL,
    ticket_ref        VARCHAR(80),
    recovered_amount  NUMERIC(12, 2),
    notes             VARCHAR(1000),
    fingerprint       VARCHAR(160)   NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_finding UNIQUE (statement_id, fingerprint)
);
CREATE INDEX ix_finding_org_status ON finding (org_id, status);

CREATE TABLE audit_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id       BIGINT       NOT NULL REFERENCES organization (id),
    user_id      BIGINT,
    actor_email  VARCHAR(254),
    action       VARCHAR(60)  NOT NULL,
    entity       VARCHAR(40)  NOT NULL,
    entity_id    BIGINT,
    detail       VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_org ON audit_event (org_id, created_at);
