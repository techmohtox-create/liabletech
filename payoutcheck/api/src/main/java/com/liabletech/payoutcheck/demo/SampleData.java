package com.liabletech.payoutcheck.demo;

import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Random;

import com.liabletech.payoutcheck.common.Csv;
import com.liabletech.payoutcheck.common.Money;
import com.liabletech.payoutcheck.common.Platform;
import com.liabletech.payoutcheck.outlet.PlatformTerms;
import com.liabletech.payoutcheck.recon.ReconciliationEngine;
import com.liabletech.payoutcheck.recon.ReconciliationEngine.ExpectedFees;

/**
 * Generates a realistic month of orders and weekly payout statements for one outlet, with the
 * kinds of leaks the engine is built to catch planted in them. Deterministic for a given anchor
 * date, so the sample files in the repository can be regenerated byte for byte.
 */
public final class SampleData {

	public static final int WEEKS = 4;

	private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");

	private SampleData() {
	}

	public record StatementFile(Platform platform, LocalDate periodStart, LocalDate periodEnd, LocalDate payoutDate, String utr,
			BigDecimal creditedAmount, String csv) {

		public String fileName() {
			return "%s-payout-%s-to-%s.csv".formatted(this.platform.name().toLowerCase(), this.periodStart, this.periodEnd);
		}

	}

	public record Dataset(String ordersCsv, List<StatementFile> statements) {
	}

	private record Order(Platform platform, String ref, LocalDateTime at, String status, BigDecimal items, BigDecimal packaging,
			BigDecimal discount) {
	}

	/** Four full Monday-to-Sunday weeks ending on the Sunday before {@code today}. */
	public static Dataset generate(LocalDate today) {
		LocalDate lastSunday = today.minusDays(today.getDayOfWeek().getValue());
		LocalDate firstMonday = lastSunday.minusDays(7L * WEEKS - 1);
		Random random = new Random(firstMonday.toEpochDay());
		List<Order> orders = new ArrayList<>();
		int[] sequence = { 481200, 7300100 };
		for (LocalDate day = firstMonday; !day.isAfter(lastSunday); day = day.plusDays(1)) {
			boolean weekend = day.getDayOfWeek().getValue() >= 6;
			for (Platform platform : Platform.values()) {
				int count = 7 + random.nextInt(6) + (weekend ? 4 : 0);
				for (int i = 0; i < count; i++) {
					int index = platform.ordinal();
					String ref = (platform == Platform.SWIGGY ? "SWG" : "ZMT") + (sequence[index]++);
					LocalTime time = random.nextBoolean() ? LocalTime.of(12 + random.nextInt(3), random.nextInt(60))
							: LocalTime.of(19 + random.nextInt(4), random.nextInt(60));
					BigDecimal items = BigDecimal.valueOf(160 + random.nextInt(90) * 10L).setScale(2);
					BigDecimal packaging = BigDecimal.valueOf(new int[] { 0, 15, 20, 25, 30 }[random.nextInt(5)]).setScale(2);
					BigDecimal discount = random.nextInt(10) < 3
							? Money.of(items.multiply(BigDecimal.valueOf(10 + random.nextInt(11))).movePointLeft(2)).min(new BigDecimal("100.00"))
							: Money.ZERO;
					int roll = random.nextInt(100);
					String status = roll < 93 ? "Delivered" : roll < 98 ? "Cancelled" : "Rejected";
					orders.add(new Order(platform, ref, LocalDateTime.of(day, time), status, items, packaging, discount));
				}
			}
		}

		List<List<?>> orderRows = new ArrayList<>();
		for (Order order : orders) {
			orderRows.add(List.of(order.ref(), order.at().format(STAMP), order.status(), order.platform().label(), order.items(),
					order.packaging(), order.discount()));
		}
		String ordersCsv = Csv.write(
				List.of("Order ID", "Order Date", "Status", "Platform", "Item Total", "Packaging Charges", "Restaurant Discount"),
				orderRows);

		List<StatementFile> statements = new ArrayList<>();
		for (int week = 0; week < WEEKS; week++) {
			LocalDate start = firstMonday.plusWeeks(week);
			LocalDate end = start.plusDays(6);
			for (Platform platform : Platform.values()) {
				List<Order> weekOrders = orders.stream()
					.filter((o) -> o.platform() == platform)
					.filter((o) -> !o.at().toLocalDate().isBefore(start) && !o.at().toLocalDate().isAfter(end))
					.toList();
				statements.add(statement(platform, week, start, end, weekOrders, new Random(start.toEpochDay() * 31 + platform.ordinal())));
			}
		}
		return new Dataset(ordersCsv, statements);
	}

	private static StatementFile statement(Platform platform, int week, LocalDate start, LocalDate end, List<Order> orders,
			Random random) {
		PlatformTerms terms = PlatformTerms.defaults(0, platform);
		List<List<?>> rows = new ArrayList<>();
		BigDecimal net = Money.ZERO;
		int delivered = 0;
		for (Order order : orders) {
			LocalDate date = order.at().toLocalDate();
			if (!order.status().equals("Delivered")) {
				Row row = new Row(order.ref(), date, order.status());
				if (order.status().equals("Rejected")) {
					row.penalty = new BigDecimal("50.00");
					row.note = "Order rejected by restaurant";
				}
				else if (random.nextInt(3) == 0) {
					row.cancellation = Money.of(order.items().multiply(new BigDecimal("0.15")));
					row.note = "Customer cancelled after acceptance";
				}
				net = net.add(row.settle());
				rows.add(row.values());
				continue;
			}
			delivered++;
			// Leaks are planted at fixed positions so each week shows a different mix.
			if (delivered == 5 + week || delivered == 31 + week * 2) {
				continue; // order never settled
			}
			if (delivered == 17 && week % 2 == 0) {
				Row row = new Row(order.ref(), date, "Cancelled");
				row.note = "Cancelled by customer";
				net = net.add(row.settle());
				rows.add(row.values()); // delivered, but settled as cancelled
				continue;
			}
			Row row = new Row(order.ref(), date, "Delivered");
			row.items = order.items();
			row.packaging = order.packaging();
			row.discount = order.discount();
			if (delivered == 23) {
				row.items = row.items.subtract(new BigDecimal("80.00")); // one dish missing from the settled value
			}
			if (delivered == 27 && week != 0) {
				row.discount = row.discount.add(new BigDecimal("60.00")); // a promotion the outlet never opted into
			}
			ExpectedFees fees = ReconciliationEngine.expectedFees(terms, row.items, row.packaging, row.discount);
			row.commission = delivered % 19 == 7 ? Money.percent(fees.netValue(), new BigDecimal("22")) : fees.commission();
			row.pg = delivered % 23 == 11 ? Money.percent(fees.netValue(), new BigDecimal("3")) : fees.pgFee();
			row.gst = Money.percent(row.commission.add(row.pg), terms.gstOnFeesPct());
			if (delivered == 35) {
				row.gst = row.gst.add(new BigDecimal("6.40")); // GST worked out on a larger fee
			}
			row.tds = week == 2 && delivered % 9 == 4 ? Money.percent(fees.netValue(), BigDecimal.ONE) : fees.tds();
			if (delivered % 13 == 3) {
				row.refund = Money.of(row.items.multiply(new BigDecimal("0.5")));
				row.note = "Customer complaint: item missing";
			}
			BigDecimal rowNet = row.settle();
			if (delivered == 41) {
				row.net = rowNet.subtract(new BigDecimal("35.00")); // net does not add up
			}
			net = net.add(row.net);
			rows.add(row.values());
			if (delivered == 9 && row.refund.signum() == 0 && week != 1) {
				// The same complaint refund recovered on two more rows.
				for (int i = 0; i < 2; i++) {
					Row refund = new Row(order.ref(), date, "Delivered");
					refund.refund = Money.of(order.items().multiply(new BigDecimal("0.4")));
					refund.note = "Customer complaint: quality";
					net = net.add(refund.settle());
					rows.add(refund.values());
				}
			}
		}
		Row ads = new Row("", null, "");
		ads.adjustment = platform == Platform.SWIGGY ? new BigDecimal("-750.00") : new BigDecimal("-500.00");
		ads.note = "Ads deduction: CPC campaign";
		net = net.add(ads.settle());
		rows.add(ads.values());
		if (week == 1 || week == 3) {
			Row misc = new Row("", null, "");
			misc.adjustment = new BigDecimal(week == 1 ? "-299.00" : "-118.00");
			misc.note = "Miscellaneous recovery";
			net = net.add(misc.settle());
			rows.add(misc.values());
		}
		BigDecimal credited = week == 2 && platform == Platform.ZOMATO ? net.subtract(new BigDecimal("412.00")) : net;
		String utr = (platform == Platform.SWIGGY ? "HDFCN" : "ICICR") + start.toString().replace("-", "") + "0" + (week + 1);
		String csv = Csv.write(List.of("Order No", "Order Date", "Order Status", "Item Total", "Packaging Charges",
				"Restaurant Discount", "Commission", "Payment Collection Charges", "Other Fees", "GST on Fees", "TCS", "TDS",
				"Customer Complaints", "Cancellation Deduction", "Penalties", "Other Adjustments", "Net Payout", "Remarks"), rows);
		return new StatementFile(platform, start, end, end.plusDays(3), utr, credited, csv);
	}

	/** One annexure row; amounts default to zero. */
	private static final class Row {

		final String ref;

		final LocalDate date;

		final String status;

		BigDecimal items = Money.ZERO;

		BigDecimal packaging = Money.ZERO;

		BigDecimal discount = Money.ZERO;

		BigDecimal commission = Money.ZERO;

		BigDecimal pg = Money.ZERO;

		BigDecimal gst = Money.ZERO;

		BigDecimal tds = Money.ZERO;

		BigDecimal refund = Money.ZERO;

		BigDecimal cancellation = Money.ZERO;

		BigDecimal penalty = Money.ZERO;

		BigDecimal adjustment = Money.ZERO;

		BigDecimal net;

		String note = "";

		Row(String ref, LocalDate date, String status) {
			this.ref = ref;
			this.date = date;
			this.status = status;
		}

		/** Sets the net payout to what the components add up to, and returns it. */
		BigDecimal settle() {
			this.net = Money.sum(this.items, this.packaging)
				.subtract(Money.sum(this.discount, this.commission, this.pg, this.gst, this.tds, this.refund, this.cancellation,
						this.penalty))
				.add(this.adjustment);
			return this.net;
		}

		List<Object> values() {
			return List.of(this.ref, this.date == null ? "" : this.date.toString(), this.status, this.items, this.packaging,
					this.discount, this.commission, this.pg, Money.ZERO, this.gst, Money.ZERO, this.tds, this.refund,
					this.cancellation, this.penalty, this.adjustment, this.net, this.note);
		}

	}

	/** Writes the sample files into a directory: {@code SampleData <dir> [yyyy-mm-dd]}. */
	public static void main(String[] args) throws IOException {
		Path dir = Path.of(args.length > 0 ? args[0] : "samples");
		LocalDate anchor = args.length > 1 ? LocalDate.parse(args[1]) : LocalDate.now();
		Dataset dataset = generate(anchor);
		Files.createDirectories(dir);
		Files.writeString(dir.resolve("orders.csv"), dataset.ordersCsv(), StandardCharsets.UTF_8);
		StringBuilder index = new StringBuilder("file,platform,period_start,period_end,payout_date,utr,credited_amount\n");
		for (StatementFile file : dataset.statements()) {
			Files.writeString(dir.resolve(file.fileName()), file.csv(), StandardCharsets.UTF_8);
			index.append(String.join(",", file.fileName(), file.platform().name(), file.periodStart().toString(),
					file.periodEnd().toString(), file.payoutDate().toString(), file.utr(), file.creditedAmount().toPlainString()))
				.append('\n');
		}
		Files.writeString(dir.resolve("statements-index.csv"), index.toString(), StandardCharsets.UTF_8);
	}

}
